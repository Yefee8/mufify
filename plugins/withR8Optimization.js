const { withAppBuildGradle, withGradleProperties } = require('expo/config-plugins');

const DEFAULT_FILE = 'getDefaultProguardFile("proguard-android.txt")';
const OPTIMIZING_FILE = 'getDefaultProguardFile("proguard-android-optimize.txt")';

/**
 * Let R8 actually optimise.
 *
 * Turning minification on in `app.json` gets shrinking and obfuscation — 1.5.0
 * shipped with 93% of its classes renamed — and **not** optimisation, because
 * of one line in a file nobody here wrote. The React Native template points
 * `proguardFiles` at AGP's `proguard-android.txt`, and line 16 of that file is:
 *
 *     -dontoptimize
 *
 * R8 honours it. So inlining, class merging, dead-branch removal and the rest
 * never ran, and Google Play reported the app back as "optimisation not
 * enabled" even with minification on. AGP ships the same defaults a second
 * time as `proguard-android-optimize.txt`, which is byte-for-byte the other
 * file without that line; swapping to it is the whole fix.
 *
 * It has to be a plugin rather than an `app.json` key: `expo-build-properties`
 * exposes `enableMinifyInReleaseBuilds` and `extraProguardRules` but not which
 * default file is used, `extraProguardRules` only ever *appends* — and nothing
 * appended can undo `-dontoptimize` — and `android/` is regenerated by
 * prebuild, so editing the generated `build.gradle` lasts until the next one.
 *
 * Idempotent, and loud when it fails: a silent no-op here is a release that
 * looks optimised and is not, which is exactly the state this exists to end.
 */
/**
 * Shrink resources inside R8 rather than after it.
 *
 * Play's second R8 note — "optimised removal of unused resources not enabled"
 * — is this flag. The ordinary shrinker runs after R8 and keeps every resource
 * referenced from any code R8 kept *or could not prove dead*; the optimised one
 * runs inside R8 and drops resources reachable only from code R8 removed. It is
 * the default from AGP 9, which Play's note suggests upgrading to, and AGP 9 is
 * not on offer: Expo SDK 57 pins 8.12. The option exists in 8.12 — checked in
 * the AGP jar, not assumed — so this turns on the thing the upgrade would have.
 */
const OPTIMIZED_RESOURCE_SHRINKING = 'android.r8.optimizedResourceShrinking';

function withOptimizedResourceShrinking(config) {
  return withGradleProperties(config, (modConfig) => {
    const properties = modConfig.modResults.filter(
      (item) => !(item.type === 'property' && item.key === OPTIMIZED_RESOURCE_SHRINKING),
    );
    properties.push({ type: 'property', key: OPTIMIZED_RESOURCE_SHRINKING, value: 'true' });
    modConfig.modResults = properties;
    return modConfig;
  });
}

module.exports = function withR8Optimization(config) {
  config = withOptimizedResourceShrinking(config);
  return withAppBuildGradle(config, (modConfig) => {
    const contents = modConfig.modResults.contents;

    if (contents.includes(OPTIMIZING_FILE)) {
      return modConfig;
    }

    if (!contents.includes(DEFAULT_FILE)) {
      throw new Error(
        'withR8Optimization: app/build.gradle no longer references ' +
          `${DEFAULT_FILE}. React Native changed the template; check which ` +
          'default ProGuard file the release build uses before shipping.',
      );
    }

    modConfig.modResults.contents = contents.replace(DEFAULT_FILE, OPTIMIZING_FILE);
    return modConfig;
  });
};
